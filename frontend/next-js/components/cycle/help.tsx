"use client";

import Box from "@cloudscape-design/components/box";
import HelpPanel from "@cloudscape-design/components/help-panel";

export function CycleHelp() {
  return (
    <HelpPanel header={<h2>改善ループ</h2>}>
      <Box variant="p">
        14 日を 1 周として、観測から改修案・下書き・承認・公開・配信までを 1 画面で見ます。
        公開・送信・配信は人が行います。この画面では、確認して OK を出し、出てきた手順（コマンド）を自分で実行します。
      </Box>
      <h3>見かた</h3>
      <ul>
        <li>上: 周の ID と期間、改修案の反映の内訳、前の周の 30 日後の判定。反映が 0 件の周には警告が出ます</li>
        <li>左: 段階 ①〜⑦。状態（済み・承認待ち・未着手・止まっている）と項目の件数</li>
        <li>右: 選んだ段階のジョブの概要と、項目の一覧。項目を選ぶと中身と確認項目が開きます</li>
      </ul>
      <h3>承認の流れ</h3>
      <ul>
        <li>確認項目をすべて入れると OK を押せます。OK の後に手順が出ます</li>
        <li>手順を行ったら「実行した」を押すと、システムが確かめます（結果は 30 秒ごとの読み直しで出ます）</li>
        <li>確かめられなかったときは理由が出ます。直して、もう一度「実行した」を押せます</li>
        <li>差し戻すときは理由（1〜500 文字）を書きます。次の周の改修案が読みます。個人情報は書かないでください</li>
        <li>改修案（PR）の項目には OK がありません。GitHub で PR を承認してマージすると進みます</li>
        <li>OK を押した後に項目の中身が差し替わったときは、エラーになります。画面を読み込み直して確かめます</li>
      </ul>
      <h3>表示しないもの</h3>
      <Box variant="p">メールの送信先は、セグメント名と件数だけを出します（コンタクトの氏名・メールアドレスは出しません）。</Box>
    </HelpPanel>
  );
}
